import assert from 'node:assert/strict';
import {verifyCandidate,sniff,probe,candidatesFromAudit} from './probe-public-data-v47.mjs';
assert.throws(()=>verifyCandidate('https://evil.example/a.csv'),/허용되지/);
assert.throws(()=>verifyCandidate('http://www.data.go.kr/a.csv'),/허용되지/);
assert.throws(()=>verifyCandidate('https://www.data.go.kr/a.pdf'),/CSV/);
const url='https://www.data.go.kr/files/example.csv';
assert.equal(sniff(new TextEncoder().encode('<html>Login</html>'),url),'html_or_xml');
const csv=new TextEncoder().encode('name,amount\nA,2\n');
const fake=async()=>new Response(csv,{headers:{'content-type':'text/csv'}});
const ok=await probe({id:'15000249',url},{fetcher:fake});
assert.equal(ok.status,'download_verified');assert.equal(ok.bytes,csv.length);
const reject=await probe({id:'15000249',url},{fetcher:async()=>new Response('<html>Access</html>',{headers:{'content-type':'text/html'}})});
assert.equal(reject.status,'not_a_file');
const large=await probe({id:'15000249',url},{fetcher:async()=>new Response('x',{headers:{'content-length':'2097153'}})});
assert.equal(large.status,'too_large');
const audit={results:[{id:'15000249',candidateLinks:[url,'https://attacker.net/data.csv']}]};
assert.deepEqual(candidatesFromAudit(audit).map(x=>x.url),[url]);
assert.deepEqual(candidatesFromAudit({results:[]}),[]);
console.log('V47 download bounds, format detection, hostile URLs and audit candidate tests passed');
