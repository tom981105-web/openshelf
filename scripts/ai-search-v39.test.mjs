import assert from 'node:assert/strict';
import fs from 'node:fs';
import worker,{sanitize} from '../worker/ai-smart-search.mjs';
const valid={query:'건물 에너지 데이터를 분석하는 도구',candidates:[{id:'15000001',type:'api',name:'에너지 정보 API',provider:'기관',summary:'전력'}]};
assert.deepEqual(sanitize(valid).candidates.map(x=>x.id),['15000001']);
assert.throws(()=>sanitize({...valid,query:'a'}),/4~400/);
assert.throws(()=>sanitize({...valid,candidates:[]}),/검색 후보/);
assert.throws(()=>sanitize({...valid,candidates:[{id:'1',type:'bad',name:'x'}]}),/잘못된/);
assert.throws(()=>sanitize({...valid,candidates:Array(13).fill(valid.candidates[0])}),/검색 후보/);
const denied=await worker.fetch(new Request('https://example.workers.dev/',{method:'POST',headers:{origin:'https://bad.example'}}),{});
assert.equal(denied.status,403);
const missingKey=await worker.fetch(new Request('https://example.workers.dev/',{method:'POST',headers:{origin:'https://tom981105-web.github.io'}}),{});
assert.equal(missingKey.status,401);
const ui=fs.readFileSync('unified-search.js','utf8'),html=fs.readFileSync('unified-search.html','utf8');
for(const id of ['aiQuestion','aiAsk','aiStatus','aiSummary','aiMatches'])assert.ok(html.includes('id="'+id+'"'));
assert.match(ui,/if\(!AI_SEARCH_ENDPOINT\)/);
assert.match(ui,/candidates\.map/);
assert.ok(!ui.includes('GEMINI_API_KEY'),'no key reference in browser JavaScript');
assert.match(fs.readFileSync('ai-search-config.js','utf8'),/AI_SEARCH_ENDPOINT=''/);
console.log('V39 optional Gemini boundary tests passed');